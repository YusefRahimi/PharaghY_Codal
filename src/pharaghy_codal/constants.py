def notice_title(code: str) -> str | None:
    """عنوان فارسی یک کد اطلاعیه (مثلاً ``ن-۳۰``)."""
    return NOTICE_CODES.get(code.strip())


def list_notice_codes(group: str | None = None) -> list[dict[str, Any]]:
    """
    لیست کدهای اطلاعیه برای نمایش در UI.

    Parameters
    ----------
    group:
        یکی از کلیدهای ``NOTICE_GROUPS`` یا ``None`` برای همه.
    """
    if group is None:
        codes = list(NOTICE_CODES.keys())
    else:
        codes = NOTICE_GROUPS.get(group, [])
    return [{"code": c, "title": NOTICE_CODES[c]} for c in codes if c in NOTICE_CODES]


def notice_group_of(code: str) -> str | None:
    """نام گروه موضوعی یک کد اطلاعیه."""
    code = code.strip()
    for g, items in NOTICE_GROUPS.items():
        if code in items:
            return g
    return None
